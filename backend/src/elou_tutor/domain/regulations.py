# Уровни severity в порядке возрастания критичности
SEVERITY_ORDER = {
    "LOW": 1,
    "MEDIUM": 2,
    "HIGH": 3,
    "CRITICAL": 4,
}


def get_max_severity(error_categories: list) -> str:
    """
    Определяет максимальный уровень severity из списка категорий ошибок.

    Параметры:
        error_categories: список ключей из ERROR_TAXONOMY (например, ['SEQUENCE_VIOLATION', 'TIMING_VIOLATION']).

    Возвращает:
        Строку severity: 'LOW', 'MEDIUM', 'HIGH' или 'CRITICAL'.
    """
    if not error_categories:
        return "LOW"
    max_sev = "LOW"
    for cat in error_categories:
        if cat in ERROR_TAXONOMY:
            sev = ERROR_TAXONOMY[cat]["severity"]
            if SEVERITY_ORDER.get(sev, 0) > SEVERITY_ORDER.get(max_sev, 0):
                max_sev = sev
    return max_sev


